BEGIN;
CREATE TABLE IF NOT EXISTS classroom_type (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 revision bigint NOT NULL DEFAULT 0,
 name varchar(60) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS classroom (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo varchar(20) NOT NULL UNIQUE,
 capacidad integer NOT NULL
);
ALTER TABLE classroom ADD COLUMN IF NOT EXISTS revision bigint NOT NULL DEFAULT 0;
ALTER TABLE classroom ADD COLUMN IF NOT EXISTS type_id integer;
INSERT INTO classroom_type(name)
 SELECT 'General' WHERE EXISTS (SELECT 1 FROM classroom WHERE type_id IS NULL)
 AND NOT EXISTS (SELECT 1 FROM classroom_type WHERE name='General');
UPDATE classroom SET type_id=(SELECT id FROM classroom_type WHERE name='General') WHERE type_id IS NULL;
ALTER TABLE classroom ALTER COLUMN type_id SET NOT NULL;
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_classroom_type' AND conrelid='classroom'::regclass) THEN
  ALTER TABLE classroom ADD CONSTRAINT fk_classroom_type FOREIGN KEY(type_id) REFERENCES classroom_type(id);
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='chk_classroom_capacity' AND conrelid='classroom'::regclass) THEN
  ALTER TABLE classroom ADD CONSTRAINT chk_classroom_capacity CHECK(capacidad>0);
 END IF;
END $$;
COMMIT;
